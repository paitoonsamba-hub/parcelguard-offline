"use strict";
// V1.5 Pilot: explicit customer orders and owner-only fulfillment.
// No automatic payment attestation, slip storage, emailing, or Cloud deployment.
const crypto=require("node:crypto");
const {onCall,HttpsError}=require("firebase-functions/v2/https");
const {getFirestore,FieldValue}=require("firebase-admin/firestore");
const {PACKAGES,validPlan}=require("./license-model");
const {STATUS,METHOD,planPrice,reference,paymentId,safeOrder}=require("./sales-model");
const db=getFirestore();
const options={region:"asia-southeast1",maxInstances:10,enforceAppCheck:false};
const sha=v=>crypto.createHash("sha256").update(v,"utf8").digest("hex");
const millis=x=>x&&typeof x.toMillis==="function"?x.toMillis():null;
function requireCustomer(req) {
  const uid=req.auth?.uid;
  if(!uid) throw new HttpsError("unauthenticated","Sign in before ordering.");
  if(req.auth.token?.email_verified!==true)
    throw new HttpsError("permission-denied","Verify your email first.");
  return uid;
}
async function requireOwner(req){
  const uid=requireCustomer(req);
  const snap=await db.collection("admins").doc(uid).get();
  if(!snap.exists||snap.get("role")!=="owner"||snap.get("disabled")===true)
    throw new HttpsError("permission-denied","Owner role required.");
  return uid;
}
function displayOrder(doc) {
  const x=doc.data();
  return safeOrder({id:doc.id,plan:x.plan,amountThb:x.amountThb,status:x.status,
    createdAt:millis(x.createdAt),fulfilledAt:millis(x.fulfilledAt)});
}
function ownerOrder(doc){
  const x=doc.data();
  return {...displayOrder(doc),customerUid:x.customerUid,customerEmail:x.customerEmail,
    paymentId:x.paymentId||null,licenseHash:x.licenseHash||null,
    fulfilledBy:x.fulfilledBy||null};
}
exports.salesCreateOrder=onCall(options,async req=>{
  const uid=requireCustomer(req);
  const plan=String(req.data?.plan||"");
  if(!validPlan(plan))throw new HttpsError("invalid-argument","Invalid package.");
  // Random ID generated by the server. Never trust price, status, UID or references from clients.
  const orderRef=db.collection("salesOrders").doc();
  const lockRef=db.collection("salesOrderThrottle").doc(uid);
  const now=Date.now();
  await db.runTransaction(async tx=>{
    const old=await tx.get(lockRef);
    const previous=millis(old.get("lastOrderAt"));
    if(previous&&now-previous<60*1000)
      throw new HttpsError("resource-exhausted","Please wait before placing another order.");
    tx.create(orderRef,{customerUid:uid,customerEmail:String(req.auth.token.email||""),
      plan,amountThb:planPrice(plan),currency:"THB",status:STATUS.PENDING,
      createdAt:FieldValue.serverTimestamp(),paymentId:null,licenseHash:null});
    tx.set(lockRef,{lastOrderAt:FieldValue.serverTimestamp()},{merge:true});
  });
  return {orderId:orderRef.id,plan,amountThb:planPrice(plan),status:STATUS.PENDING,
    message:"Order received. Pay only to verified seller details; never post slips publicly."};
});
exports.salesListMyOrders=onCall(options,async req=>{
  const uid=requireCustomer(req);
  const snap=await db.collection("salesOrders").where("customerUid","==",uid).limit(40).get();
  const rows=snap.docs.map(displayOrder);
  rows.sort((a,b)=>(b.createdAt||0)-(a.createdAt||0));
  return {items:rows};
});
exports.salesAdminListOrders=onCall(options,async req=>{
  await requireOwner(req);
  const snap=await db.collection("salesOrders").orderBy("createdAt","desc").limit(50).get();
  return {items:snap.docs.map(ownerOrder)};
});
// The ONLY issuance path for salesOrders. Owner must independently verify money in the bank.
// Transaction atomically prevents duplicate fulfillment and duplicate payment reference.
// Plaintext license returned once to owner; it is NEVER saved in Firestore.
exports.salesAdminFulfillOrder=onCall(options,async req=>{
  const uid=await requireOwner(req);
  const orderId=String(req.data?.orderId||"");
  if(!/^[A-Za-z0-9]{12,36}$/.test(orderId))
    throw new HttpsError("invalid-argument","Invalid order ID.");
  if(req.data?.manuallyChecked!==true)
    throw new HttpsError("failed-precondition","Review actual bank transaction first.");
  const method=String(req.data?.method||"");
  if(!METHOD.includes(method))throw new HttpsError("invalid-argument","Invalid payment method.");
  let ref;
  try{ref=reference(req.data?.reference);}catch(e){throw new HttpsError("invalid-argument",e.message);}
  const id=paymentId(method,ref);
  const orderRef=db.collection("salesOrders").doc(orderId);
  const paymentRef=db.collection("manualPayments").doc(id);
  const key="PG-"+crypto.randomBytes(16).toString("hex").toUpperCase();
  const licenseHash=sha(key);
  const keyRef=db.collection("licenseKeys").doc(licenseHash);
  await db.runTransaction(async tx=>{
    const [orderSnap,existingPayment]=await Promise.all([tx.get(orderRef),tx.get(paymentRef)]);
    if(!orderSnap.exists)throw new HttpsError("not-found","Order not found.");
    const order=orderSnap.data();
    if(order.status!==STATUS.PENDING||order.licenseHash)
      throw new HttpsError("already-exists","Order already fulfilled.");
    if(existingPayment.exists)
      throw new HttpsError("already-exists","Payment reference already recorded.");
    if(!validPlan(order.plan)||order.amountThb!==PACKAGES[order.plan].priceThb)
      throw new HttpsError("failed-precondition","Order pricing mismatch.");
    const approvedAmount=Number(req.data?.amountThb);
    if(!Number.isInteger(approvedAmount)||approvedAmount!==order.amountThb)
      throw new HttpsError("failed-precondition","Bank amount does not match order.");
    tx.create(paymentRef,{plan:order.plan,amountThb:order.amountThb,method,
      reference:ref,manuallyChecked:true,recordedBy:uid,
      recordedAt:FieldValue.serverTimestamp(),issuedKeyHash:licenseHash,
      issuedAt:FieldValue.serverTimestamp(),issuedBy:uid,orderId});
    tx.create(keyRef,{licenseType:"lifetime",plan:order.plan,
      priceThb:order.amountThb,currency:"THB",redeemedBy:null,
      createdAt:FieldValue.serverTimestamp(),issuedVia:"sales-v1.5-owner",
      issuedBy:uid,paymentId:id,orderReference:orderId});
    tx.update(orderRef,{status:STATUS.FULFILLED,paymentId:id,licenseHash,
      fulfilledAt:FieldValue.serverTimestamp(),fulfilledBy:uid});
    tx.create(db.collection("adminAudit").doc(),{action:"fulfill_sales_order",
      actorUid:uid,orderId,paymentId:id,licenseHash,plan:order.plan,
      timestamp:FieldValue.serverTimestamp()});
  });
  return {orderId,key,licenseHash,plan:null,
    message:"Copy this key now. It cannot be retrieved after this screen closes."};
});
